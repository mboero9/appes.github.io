const menuButton = document.querySelector('.menu-toggle');
const mainMenu = document.querySelector('.main-nav');
const languageButtons = [...document.querySelectorAll('[data-lang]')];
const workspaceTabs = [...document.querySelectorAll('[data-mode]')];
const workspacePanel = document.querySelector('#workspace-panel');
const workspaceQueryLabel = document.querySelector('#workspace-query-label');
const workspaceQueryText = document.querySelector('#workspace-query-text');
const workspaceSources = document.querySelector('#workspace-sources');
let currentMode = 'legal';
let currentLanguage = 'es';

try {
  currentLanguage = localStorage.getItem('appes-language') === 'en' ? 'en' : 'es';
} catch (_) {
  currentLanguage = 'es';
}

const translate = key => translations[currentLanguage][key] || translations.es[key] || key;

function updateWorkspace(animate = true) {
  const content = workspaceContent[currentLanguage][currentMode];
  workspaceQueryLabel.textContent = content.label;
  workspaceQueryText.textContent = content.query;
  workspaceSources.innerHTML = content.sources.map((source, index) => (
    `<li><span>${String(index + 1).padStart(2, '0')}</span><span>${source}</span><b aria-hidden="true">↗</b></li>`
  )).join('');

  workspaceTabs.forEach(tab => {
    const selected = tab.dataset.mode === currentMode;
    tab.classList.toggle('active', selected);
    tab.setAttribute('aria-selected', String(selected));
    tab.tabIndex = selected ? 0 : -1;
  });

  const activeTab = workspaceTabs.find(tab => tab.dataset.mode === currentMode);
  workspacePanel.setAttribute('aria-labelledby', activeTab.id);
  if (animate) {
    workspacePanel.classList.remove('is-changing');
    void workspacePanel.offsetWidth;
    workspacePanel.classList.add('is-changing');
  }
}

function updateMenuLabel() {
  const isOpen = menuButton?.getAttribute('aria-expanded') === 'true';
  menuButton?.setAttribute('aria-label', translate(isOpen ? 'closeMenu' : 'openMenu'));
}

function setLanguage(language, persist = true) {
  currentLanguage = language === 'en' ? 'en' : 'es';
  document.documentElement.lang = currentLanguage;
  document.title = translate('pageTitle');
  document.querySelector('meta[name="description"]')?.setAttribute('content', translate('pageDescription'));

  document.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = translate(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    element.innerHTML = translate(element.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(element => {
    element.setAttribute('aria-label', translate(element.dataset.i18nAria));
  });

  languageButtons.forEach(button => {
    const selected = button.dataset.lang === currentLanguage;
    button.classList.toggle('active', selected);
    button.setAttribute('aria-pressed', String(selected));
  });

  updateMenuLabel();
  updateWorkspace(false);
  if (persist) {
    try { localStorage.setItem('appes-language', currentLanguage); } catch (_) { /* Storage may be unavailable. */ }
  }
}

languageButtons.forEach(button => {
  button.addEventListener('click', () => setLanguage(button.dataset.lang));
});

workspaceTabs.forEach(tab => {
  tab.addEventListener('click', () => {
    currentMode = tab.dataset.mode;
    updateWorkspace();
  });
  tab.addEventListener('keydown', event => {
    if (!['ArrowLeft', 'ArrowRight'].includes(event.key)) return;
    event.preventDefault();
    const direction = event.key === 'ArrowRight' ? 1 : -1;
    const nextIndex = (workspaceTabs.indexOf(tab) + direction + workspaceTabs.length) % workspaceTabs.length;
    currentMode = workspaceTabs[nextIndex].dataset.mode;
    updateWorkspace();
    workspaceTabs[nextIndex].focus();
  });
});

if (menuButton && mainMenu) {
  const closeMenu = () => {
    menuButton.setAttribute('aria-expanded', 'false');
    mainMenu.classList.remove('open');
    document.body.classList.remove('menu-open');
    updateMenuLabel();
  };

  menuButton.addEventListener('click', () => {
    const isOpen = menuButton.getAttribute('aria-expanded') === 'true';
    menuButton.setAttribute('aria-expanded', String(!isOpen));
    mainMenu.classList.toggle('open', !isOpen);
    document.body.classList.toggle('menu-open', !isOpen);
    updateMenuLabel();
  });

  mainMenu.querySelectorAll('a').forEach(link => link.addEventListener('click', closeMenu));
  window.addEventListener('resize', () => {
    if (window.innerWidth > 980) closeMenu();
  });
}

document.querySelector('#year').textContent = new Date().getFullYear();

if ('IntersectionObserver' in window) {
  const observer = new IntersectionObserver((entries, io) => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add('visible');
      io.unobserve(entry.target);
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -36px' });
  document.querySelectorAll('.reveal').forEach(element => observer.observe(element));
} else {
  document.querySelectorAll('.reveal').forEach(element => element.classList.add('visible'));
}

setLanguage(currentLanguage, false);
